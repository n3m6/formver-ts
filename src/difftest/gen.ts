/**
 * Seeded input generation and spec evaluation for the differential test
 * (specification 6.8, milestone 9).
 *
 * Two jobs live here:
 *
 *   1. `generateInputs(fn)` produces candidate argument lists for one verified
 *      function, with a seeded PRNG (no packages): integers from `[-1000, 1000]` plus the
 *      edge values `0`, `±1` and `±(2^53 - 1)`, arrays of length 0 to 8, and one variant of
 *      each union.  A candidate is accepted only when **every** `@pre` of the function
 *      evaluates to `true` on it; otherwise the candidate is rejected and another one is
 *      drawn, up to a bounded number of attempts per input (after which the input is
 *      *given up* and reported, never silently replaced by an input that violates `@pre`).
 *
 *   2. `evaluateSpec` evaluates the extractor's spec-expression AST (`ExprIR`) against
 *      ordinary JS values — the same values the original function is called with.  That is
 *      the one evaluator for `@pre` *and* `@post`; there are no per-example predicates.
 *
 * The generated values are JS values (`number`, arrays, union objects), not kernel values:
 * the differential test compares the elaborated term's behaviour with the *original JS
 * function's*, so the inputs have to be what that function takes.
 */
import { SAFE_MAX } from "../kernel/index";
import type { ExprIR, FunctionIR, TypeIR, UnionIR } from "../extract/fragment";

// ---------------------------------------------------------------------------
// The PRNG
// ---------------------------------------------------------------------------

/** A small deterministic generator (`mulberry32`); the same seed gives the same stream. */
export class Rng {
  private state: number;

  constructor(seed: number) {
    // `>>> 0` keeps the state an unsigned 32-bit integer; the constant is the golden ratio.
    this.state = (seed >>> 0) + 0x9e3779b9;
  }

  /** The next 32-bit unsigned integer. */
  nextBits(): number {
    this.state = (this.state + 0x6d2b79f5) >>> 0;
    let t = this.state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return (t ^ (t >>> 14)) >>> 0;
  }

  /** A float in `[0, 1)`. */
  next(): number {
    return this.nextBits() / 0x100000000;
  }

  /** An integer in `[min, maxExclusive)`. */
  int(min: number, maxExclusive: number): number {
    if (maxExclusive <= min) return min;
    return min + Math.floor(this.next() * (maxExclusive - min));
  }

  /** True with probability `p`. */
  bool(p: number): boolean {
    return this.next() < p;
  }

  /** One element of a non-empty list. */
  pick<T>(items: readonly T[]): T {
    return items[this.int(0, items.length)]!;
  }
}

/** A generator for one seed. */
export function makeRng(seed: number): Rng {
  return new Rng(seed);
}

// ---------------------------------------------------------------------------
// Values
// ---------------------------------------------------------------------------

/** A value the generator can produce: what the original JS function is called with. */
export type InputValue = number | boolean | string | readonly InputValue[] | InputObject;

export interface InputObject {
  readonly [field: string]: InputValue;
}

/** The integers the generator proposes beyond the uniform range (specification 6.8). */
export const EDGE_INTS: readonly bigint[] = [0n, 1n, -1n, SAFE_MAX, -SAFE_MAX];

/** The uniform integer range. */
export const INT_RANGE: readonly [number, number] = [-1000, 1000];

/** The array lengths the generator uses. */
export const MAX_ARRAY_LENGTH = 8;

/**
 * A value of `type`.
 *
 * `generic` is a type parameter used only as an array element type; the only values a
 * verified function can be handed there are numbers, so the generator produces integers.
 */
export function generateValue(type: TypeIR, rng: Rng): InputValue {
  switch (type.kind) {
    case "int":
    case "generic":
      return generateInt(rng);
    case "boolean":
      return rng.bool(0.5);
    case "vec": {
      const length = rng.int(0, MAX_ARRAY_LENGTH + 1);
      const out: InputValue[] = [];
      for (let i = 0; i < length; i += 1) out.push(generateValue(type.elem!, rng));
      return out;
    }
    case "union":
      return generateUnion(type.union!, rng);
  }
}

/** An integer: an edge value with probability 0.4, otherwise uniform in `[-1000, 1000]`. */
export function generateInt(rng: Rng): number {
  if (rng.bool(0.4)) return Number(rng.pick(EDGE_INTS));
  return rng.int(INT_RANGE[0], INT_RANGE[1] + 1);
}

/** One variant of `union`, chosen uniformly, with every field generated by its type. */
export function generateUnion(union: UnionIR, rng: Rng): InputObject {
  const variant = rng.pick(union.variants);
  const out: Record<string, InputValue> = { [union.discriminant]: variant.tag };
  for (const field of variant.fields) out[field.name] = generateValue(field.type, rng);
  return out;
}

// ---------------------------------------------------------------------------
// Spec evaluation over JS values
// ---------------------------------------------------------------------------

/**
 * What a spec expression can evaluate to.  The JS values a spec reads (a parameter, an array
 * element, `result`) are `number`s, arrays and union objects; the arithmetic nodes produce
 * `bigint`s, so numeric comparisons never lose precision.  `undefined` means "not evaluable
 * here".
 */
export type SpecValue = bigint | number | boolean | string | null | readonly unknown[] | InputObject;

/** A value read out of the environment, as a spec value (`undefined` stays "not there"). */
function asSpecValue(value: unknown): SpecValue | undefined {
  return value === undefined ? undefined : (value as SpecValue);
}

/**
 * The values a spec expression reads.  `byId` is keyed by binder id (the extractor's own
 * identity for a variable) and `byName` by the surface name; `result` is the value a
 * `@post`'s `result` refers to.
 */
export interface SpecEnv {
  readonly byId: ReadonlyMap<number, unknown>;
  readonly byName: ReadonlyMap<string, unknown>;
  readonly payloads: ReadonlyMap<number, unknown>;
  readonly result?: unknown;
}

/** The environment for evaluating `fn`'s specs on one input (and optionally its result). */
export function specEnvFor(
  fn: FunctionIR,
  values: readonly InputValue[],
  result?: InputValue,
): SpecEnv {
  const byId = new Map<number, unknown>();
  const byName = new Map<string, unknown>();
  fn.params.forEach((param, index) => {
    const value = values[index];
    byId.set(param.binder.id, value);
    byName.set(param.name, value);
    for (const extra of param.extra) {
      // The length of a vector parameter is what the spec's `a.length` denotes.
      if (extra.role === "vec-len") {
        const length = Array.isArray(value) ? value.length : undefined;
        byId.set(extra.id, length);
        byName.set(extra.name, length);
      }
    }
  });
  if (result !== undefined) {
    const binder = fn.signature.result.binder;
    if (binder !== undefined) {
      // For a vector result the binder is the *length*; `result` itself is the vector.
      const length = fn.signature.result.layout.shape === "vec" && Array.isArray(result) ? result.length : result;
      byId.set(binder.id, length);
    }
  }
  return { byId, byName, payloads: new Map(), result };
}

function num(value: unknown): bigint | undefined {
  if (typeof value === "bigint") return value;
  if (typeof value === "number" && Number.isSafeInteger(value)) return BigInt(value);
  return undefined;
}

function bool(value: unknown): boolean | undefined {
  return typeof value === "boolean" ? value : undefined;
}

/**
 * Evaluate a spec expression against JS values.
 *
 * Anything the evaluator cannot read (a `state` slot, an object literal, a value that is not
 * there) yields `undefined`: the caller treats that as "the spec cannot be checked here",
 * which for `@pre` means the candidate input is rejected and for `@post` means a failure is
 * reported rather than passed over.
 */
export function evaluateSpec(e: ExprIR, env: SpecEnv): SpecValue | undefined {
  const numOf = (node: ExprIR): bigint | undefined => num(evaluateSpec(node, env));
  const boolOf = (node: ExprIR): boolean | undefined => bool(evaluateSpec(node, env));
  const cmp = (node: ExprIR, f: (a: bigint, b: bigint) => boolean): boolean | undefined => {
    const a = numOf(node.args[0]!);
    const b = numOf(node.args[1]!);
    return a === undefined || b === undefined ? undefined : f(a, b);
  };

  switch (e.kind) {
    case "int":
      return e.literal as bigint;
    case "bool":
      return e.literal === true;
    case "string":
      return e.literal as string;
    case "true":
      return true;
    case "ref": {
      const slot = e.slot;
      if (slot === undefined) return undefined;
      switch (slot.kind) {
        case "result":
          return asSpecValue(env.result);
        case "payload":
          return asSpecValue(env.payloads.get(slot.payload.id));
        case "state":
          return undefined;
        case "binder": {
          const byId = env.byId.get(slot.binder.id);
          if (byId !== undefined) return asSpecValue(byId);
          return asSpecValue(env.byName.get(slot.binder.surface ?? slot.binder.name));
        }
      }
      return undefined;
    }
    case "field": {
      const object = evaluateSpec(e.args[0]!, env);
      if (typeof object !== "object" || object === null || Array.isArray(object)) return undefined;
      return asSpecValue((object as InputObject)[e.field!.name]);
    }
    case "length": {
      // `a.length` and `result.length` are the JS array's length, the same number the
      // extractor maps to the vector's length argument.
      const object = evaluateSpec(e.args[0]!, env);
      if (Array.isArray(object)) return BigInt(object.length);
      const declared = e.vecLength === undefined ? undefined : numOf(e.vecLength);
      return declared;
    }
    case "index": {
      const object = evaluateSpec(e.args[0]!, env);
      const index = numOf(e.args[1]!);
      if (!Array.isArray(object) || index === undefined || index < 0n || index >= BigInt(object.length)) {
        return undefined;
      }
      return asSpecValue(object[Number(index)]);
    }
    case "slice": {
      const object = evaluateSpec(e.args[0]!, env);
      const from = numOf(e.args[1]!);
      const to = numOf(e.args[2]!);
      if (!Array.isArray(object) || from === undefined || to === undefined) return undefined;
      return object.slice(Number(from), Number(to));
    }
    case "append": {
      const left = evaluateSpec(e.args[0]!, env);
      const right = evaluateSpec(e.args[1]!, env);
      return Array.isArray(left) && Array.isArray(right) ? [...left, ...right] : undefined;
    }
    case "neg": {
      const value = numOf(e.args[0]!);
      return value === undefined ? undefined : -value;
    }
    case "not": {
      const value = boolOf(e.args[0]!);
      return value === undefined ? undefined : !value;
    }
    case "add":
    case "sub":
    case "mul": {
      const a = numOf(e.args[0]!);
      const b = numOf(e.args[1]!);
      if (a === undefined || b === undefined) return undefined;
      return e.kind === "add" ? a + b : e.kind === "sub" ? a - b : a * b;
    }
    case "lt":
      return cmp(e, (a, b) => a < b);
    case "le":
      return cmp(e, (a, b) => a <= b);
    case "gt":
      return cmp(e, (a, b) => a > b);
    case "ge":
      return cmp(e, (a, b) => a >= b);
    case "eq":
    case "neq": {
      const a = evaluateSpec(e.args[0]!, env);
      const b = evaluateSpec(e.args[1]!, env);
      if (a === undefined || b === undefined) return undefined;
      const aNum = num(a);
      const bNum = num(b);
      const equal =
        aNum !== undefined && bNum !== undefined
          ? aNum === bNum
          : typeof a === "string" && typeof b === "string"
            ? a === b
            : false;
      return e.kind === "eq" ? equal : !equal;
    }
    case "and": {
      const a = boolOf(e.args[0]!);
      if (a === undefined) return undefined;
      if (!a) return false;
      return boolOf(e.args[1]!);
    }
    case "or": {
      const a = boolOf(e.args[0]!);
      if (a === undefined) return undefined;
      if (a) return true;
      return boolOf(e.args[1]!);
    }
    case "cond": {
      const cond = e.cond;
      if (cond === undefined || cond.thenExpr === undefined || cond.elseExpr === undefined) return undefined;
      const test = boolOf(cond.expr);
      if (test === undefined) return undefined;
      return evaluateSpec(test ? cond.thenExpr : cond.elseExpr, env);
    }
    case "inRange": {
      const value = numOf(e.args[0]!);
      return value === undefined ? undefined : -SAFE_MAX <= value && value <= SAFE_MAX;
    }
    case "call": {
      const builtin = e.callee?.builtin;
      if (builtin === undefined) return undefined;
      const args = e.args.map((arg) => numOf(arg));
      if (args.some((arg) => arg === undefined)) return undefined;
      const [first, second] = args as bigint[];
      switch (builtin.kind) {
        case "max":
          return first! >= second! ? first! : second!;
        case "min":
          return first! <= second! ? first! : second!;
        case "abs":
          return first! < 0n ? -first! : first!;
        case "floor":
          return second === undefined || second <= 0n ? undefined : floorDiv(first!, second);
        case "trunc":
          return second === undefined || second <= 0n ? undefined : first! / second!;
      }
      return undefined;
    }
    case "projection": {
      const object = evaluateSpec(e.args[0]!, env);
      if (typeof object !== "object" || object === null || Array.isArray(object)) return undefined;
      let out: unknown = object;
      for (const step of e.projPath ?? []) {
        const record = out as Record<string, unknown>;
        out = step === 0 ? record.first : record.second;
      }
      return asSpecValue(out);
    }
    case "tagTest": {
      const subject = evaluateSpec(
        { ...e, kind: "ref", slot: e.slot, args: [], sites: [], facts: [] },
        env,
      );
      if (typeof subject !== "object" || subject === null || Array.isArray(subject)) return undefined;
      const actual = (subject as InputObject)[e.union!.discriminant];
      const matches = actual === e.variant!.tag;
      return e.literal === true ? matches : !matches;
    }
    case "object":
      return undefined;
  }
}

/** `floor(e / k)` on bigints (JS bigint division truncates towards zero). */
function floorDiv(e: bigint, k: bigint): bigint {
  const q = e / k;
  return e % k !== 0n && e < 0n !== k < 0n ? q - 1n : q;
}

// ---------------------------------------------------------------------------
// Input generation
// ---------------------------------------------------------------------------

export interface GenerateOptions {
  /** The PRNG seed; the same seed gives the same inputs for the same function. */
  readonly seed?: number;
  /** How many inputs to produce. */
  readonly count?: number;
  /** How many candidates to try per input before giving up on it. */
  readonly maxAttempts?: number;
}

/** What generation produced, with the numbers a caller wants to report. */
export interface GeneratedInputs {
  readonly seed: number;
  readonly count: number;
  /** The accepted inputs, each one argument list (in parameter order). */
  readonly inputs: readonly (readonly InputValue[])[];
  /** Candidates drawn (accepted + rejected). */
  readonly attempts: number;
  /** Candidates a `@pre` rejected. */
  readonly rejected: number;
  /** Inputs no candidate satisfied `@pre` for (bounded by `maxAttempts` each). */
  readonly givenUp: number;
}

/** The default seed: a fixed value, so a failing input can be reproduced. */
export const DEFAULT_SEED = 20261009;

/** The default number of inputs per function (specification 6.8). */
export const DEFAULT_INPUT_COUNT = 200;

/** The default attempt budget per input. */
export const DEFAULT_MAX_ATTEMPTS = 100;

/** The parameter values of one candidate, in parameter order. */
export function generateCandidate(fn: FunctionIR, rng: Rng): InputValue[] {
  return fn.params.map((param) => generateValue(param.type, rng));
}

/**
 * True when every `@pre` of `fn` holds on `values`.  A `@pre` the evaluator cannot read
 * counts as *not* holding: the differential test only calls the original function with
 * inputs whose preconditions it has actually checked.
 */
export function preconditionsHold(fn: FunctionIR, values: readonly InputValue[]): boolean {
  const env = specEnvFor(fn, values);
  for (const pre of fn.signature.preconditions) {
    if (evaluateSpec(pre.prop, env) !== true) return false;
  }
  return true;
}

/**
 * `count` inputs for `fn`, each one satisfying every `@pre`.  Candidates that violate a
 * `@pre` are rejected and redrawn; after `maxAttempts` the input is given up (the report
 * says how many).  The result is deterministic in `seed`.
 */
export function generateInputs(fn: FunctionIR, options: GenerateOptions = {}): GeneratedInputs {
  const seed = options.seed ?? DEFAULT_SEED;
  const count = options.count ?? DEFAULT_INPUT_COUNT;
  const maxAttempts = options.maxAttempts ?? DEFAULT_MAX_ATTEMPTS;
  const rng = makeRng(seed);
  const inputs: InputValue[][] = [];
  let attempts = 0;
  let rejected = 0;
  let givenUp = 0;
  for (let index = 0; index < count; index += 1) {
    let accepted: InputValue[] | undefined;
    for (let attempt = 0; attempt < maxAttempts; attempt += 1) {
      attempts += 1;
      const candidate = generateCandidate(fn, rng);
      if (preconditionsHold(fn, candidate)) {
        accepted = candidate;
        break;
      }
      rejected += 1;
    }
    if (accepted === undefined) givenUp += 1;
    else inputs.push(accepted);
  }
  return { seed, count, inputs, attempts, rejected, givenUp };
}
